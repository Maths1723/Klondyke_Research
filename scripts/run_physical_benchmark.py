"""Does modelling grain counting beat kriging raw assays at recovering the geology?

Synthetic creek where assays are generated by drawing gold grains from
churn-drill-sized samples (sampling.py). Because the true concentration field
is known, every method is scored on what an operator needs - the in-situ
concentration log c at held-out locations - not on reproducing noisy assays.

Methods (all on valley coordinates s, n):
  kriging_loggrade  ordinary kriging of log1p(grade mg/m3), anisotropy from
                    directional variograms; latent sd = kriging sd minus nugget
  gp_loggrade       Gaussian-likelihood GP (Matern-3/2, ARD) on the same target
  cpg_field         latent log-concentration GP + exact compound Poisson-gamma
                    likelihood (physical.CPGField). Grain parameters are fitted
                    once on all holes and held fixed across folds (they are
                    global physical constants); kernel parameters are refitted
                    in every fold.

Scores at held-out holes vs TRUE log c: RMSE, Spearman, bias, 90% coverage,
CRPS of the latent prediction. Also: calibration of predicted P(zero assay).

Usage: python scripts/run_physical_benchmark.py [--seed 11] [--folds 10]
Outputs: reports/physical_benchmark.csv, reports/physical_benchmark.json,
         reports/figures/physical_*.png
"""

from __future__ import annotations

import argparse
import json
import sys
import time
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import norm, spearmanr

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from klondyke import baselines as B  # noqa: E402
from klondyke import cv, metrics, models, physical, sampling, synthetic, units, valley  # noqa: E402

warnings.filterwarnings("ignore")


def log(msg):
    print(time.strftime("%H:%M:%S"), msg, flush=True)


def score(truth, mu, sd):
    gold = np.exp(truth)
    order = np.argsort(-mu)
    top20 = float(gold[order[: int(np.ceil(0.2 * len(mu)))]].sum() / gold.sum())
    chan = truth > np.percentile(truth, 80)            # true top-20% (channel) holes
    rho_chan = float(spearmanr(truth[chan], mu[chan]).statistic)
    return {"top20_gold": top20, "spearman_in_channel": rho_chan,
            "rmse": float(np.sqrt(np.mean((mu - truth) ** 2))),
            "bias": float(np.mean(mu - truth)),
            "spearman": float(spearmanr(truth, mu).statistic),
            "crps": float(np.mean(metrics.crps_gaussian(truth, mu, sd))),
            "cov90": float(np.mean(np.abs(truth - mu) <= 1.6449 * sd)),
            "cov50": float(np.mean(np.abs(truth - mu) <= 0.6745 * sd))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--folds", type=int, default=10)
    ap.add_argument("--micro-sd", type=float, default=0.0)
    a = ap.parse_args()

    df, truth = synthetic.make_physical_dataset(synthetic.PhysParams(seed=a.seed, micro_sd=a.micro_sd))
    kind, s, st, V = sampling.observations_from_grade(df.grade_cents_yd3, df.dredge_section_ft)
    poly = valley.centreline_from_drill_lines(df.x.values, df.y.values, df.claim_no.values)
    sv, nv = valley.project_to_centreline(df.x.values, df.y.values, poly)
    sv -= sv.min()
    X = np.column_stack([sv, nv])
    g_mg = units.cents_per_yd3_to_mg_per_m3(df.grade_cents_yd3.values)
    y = np.log1p(g_mg)
    T = df.logc_true.values
    log(f"{len(df)} holes; zeros {np.mean(kind==0):.1%}, trace {np.mean(kind==1):.1%}; "
        f"median grains/sample {np.median(df.grains):.0f}")

    log("full-data CPG fit (grain parameters)...")
    full = physical.CPGField(maxiter=80).fit(X, kind, s, st, V)
    fs = full.summary()
    log(f"  {fs}")

    schemes = {"LOLO": list(cv.grouped_line_folds(df.line_id.values, n_folds=a.folds, seed=a.seed)),
               "block1000m": list(cv.along_valley_blocks(sv, 1000.0, 150.0))}
    rows, preds = [], {}
    warm = {k: fs[k] for k in ("sigma", "ls_s", "ls_n", "beta0")}
    for sch, splits in schemes.items():
        out = {k: (np.full(len(y), np.nan), np.full(len(y), np.nan)) for k in
               ["kriging_loggrade", "gp_loggrade", "cpg_field"]}
        pz = np.full(len(y), np.nan)
        for i, (tr, te) in enumerate(splits):
            t0 = time.time()
            k = B.OrdinaryKriging(anisotropy="auto").fit(X[tr], y[tr])
            m_, s_ = k.predict_latent(X[te]); out["kriging_loggrade"][0][te] = m_; out["kriging_loggrade"][1][te] = s_
            g = models.AnisotropicGP(n_restarts=0).fit(X[tr], y[tr])
            m_, s_ = g.predict_latent(X[te]); out["gp_loggrade"][0][te] = m_; out["gp_loggrade"][1][te] = s_
            c = physical.CPGField(fit_grain=False, maxiter=30,
                                  init={"mbar": fs["mbar"], "alpha": fs["alpha"]}).fit(
                X[tr], kind[tr], s[tr], st[tr], V[tr], theta0=warm)
            m_, s_ = c.predict_latent(X[te]); out["cpg_field"][0][te] = m_; out["cpg_field"][1][te] = s_
            # predicted probability of a zero assay at the held-out holes
            ff = m_[None, :] + s_[None, :] * np.random.default_rng(i).standard_normal((400, len(te)))
            pz[te] = np.exp(-np.exp(ff) * V[te] / fs["mbar"]).mean(0)
            log(f"{sch} fold {i+1}/{len(splits)}  {time.time()-t0:.0f}s")
        for name, (m_, s_) in out.items():
            r = score(T, m_, s_); r.update(method=name, scheme=sch); rows.append(r)
            preds[(name, sch)] = (m_, s_)
        z = kind == 0
        rows.append({"method": "cpg_field", "scheme": sch, "p_zero_pred_mean": float(np.nanmean(pz)),
                     "p_zero_obs": float(z.mean()),
                     "brier_zero": float(np.nanmean((pz - z) ** 2)),
                     "brier_zero_climatology": float(np.mean((z.mean() - z) ** 2))})
    res = pd.DataFrame(rows)
    tag = f"_seed{a.seed}"
    res.to_csv(ROOT / "reports" / f"physical_benchmark{tag}.csv", index=False)
    np.savez(ROOT / "data" / "interim" / f"physical_preds{tag}.npz", T=T, y=y, kind=kind, V=V, X=X,
             **{f"{k[0]}__{k[1]}__mu": v[0] for k, v in preds.items()},
             **{f"{k[0]}__{k[1]}__sd": v[1] for k, v in preds.items()})
    (ROOT / "reports" / f"physical_benchmark{tag}.json").write_text(json.dumps(
        {"seed": a.seed, "micro_sd": a.micro_sd, "true": {"mbar": 1.0, "alpha": 0.6,
         "m_eff": float(sampling.grain_params(1.0, 0.6)[1])}, "cpg_full_fit": fs}, indent=2))
    print(res.round(3).to_string())
    plot(df, X, T, preds, full, truth, poly)


def plot(df, X, T, preds, full, truth, poly):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axs = plt.subplots(1, 3, figsize=(14, 4.2), sharey=True)
    for ax, name in zip(axs, ["kriging_loggrade", "gp_loggrade", "cpg_field"]):
        m_, _ = preds[(name, "LOLO")]
        ax.scatter(T, m_, s=6, alpha=0.5)
        lim = [min(T.min(), np.nanmin(m_)) - 0.3, max(T.max(), np.nanmax(m_)) + 0.3]
        ax.plot(lim, lim, "k--", lw=0.8)
        ax.set_title(f"{name}\nRMSE {np.sqrt(np.nanmean((m_-T)**2)):.2f}  ρ {spearmanr(T, m_).statistic:.2f}")
        ax.set_xlabel("true ln c (mg/m³)")
    axs[0].set_ylabel("predicted at held-out drill line")
    fig.suptitle("Recovering in-situ gold concentration from grain-counting assays (leave-one-line-out)")
    fig.tight_layout(); fig.savefig(ROOT / "reports" / "figures" / "physical_truth_recovery.png", dpi=150)
    plt.close(fig)


if __name__ == "__main__":
    main()
